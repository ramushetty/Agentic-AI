# Tools



# Tools extend what agents can do—letting them fetch real-time data, execute code, query external databases, and take actions in the world.

# Under the hood, tools are callable functions with well-defined inputs and outputs that get passed to a chat model. The model decides when
#  to invoke a tool based on the conversation context, and what input arguments to provide.


from langchain.tools import tool

@tool
def search_database(query: str, limit: int = 10) -> str:
    """Search the customer database for records matching the query.

    Args:
        query: Search terms to look for
        limit: Maximum number of results to return
    """
    return f"Found {limit} results for '{query}'"

